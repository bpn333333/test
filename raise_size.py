# -*- coding: utf-8 -*-
"""調達額を下げるとシードの倍率はどうなるか

結論を先に書くと、倍率を決めるのは「調達額」ではなく「キャップ＋調達額」。
調達額だけ下げても分母がわずかにしか減らないので、倍率はほとんど動かない。

⚠ 検討用。README.md の確定値ではない。
"""

# J-KISS がポストマネー・キャップだとすると、転換時のシード持分は
#     s0 = X / (C + X)          X=調達額, C=キャップ
# その後の希薄化（シリーズA・ESOP補充・IPO公募）を一括で d とすると
#     最終持分 = s0 * d
#     倍率     = s0 * d * V / X = d * V / (C + X)
# → X は分母の一部にしか出てこない。効くのは C。

# 現計画（キャップ6億・調達1.42億）で上場後シード14.5% になるところから d を逆算
C0, X0, SHARE0 = 6.0, 1.42, 0.145
D = SHARE0 * (C0 + X0) / X0
print("希薄化係数 d = %.3f （シリーズA・ESOP補充・IPO公募をまとめたもの）" % D)
print()


def multiple(V_oku, cap, raise_oku):
    """V_oku: 上場時の時価総額（億）"""
    return D * V_oku / (cap + raise_oku)


def share(cap, raise_oku):
    return raise_oku / (cap + raise_oku) * D


V = 136.6   # P4主役案・全社PSR7倍のときの時価総額（億）

print("=" * 82)
print("① 調達額だけ下げる（キャップは6億のまま・時価総額 %.1f億）" % V)
print("=" * 82)
print("  調達額    シード持分    取り分      倍率     1年目の所要 1.15億を賄えるか")
print("  " + "-" * 72)
for x in [1.42, 1.20, 1.00, 0.80, 0.50]:
    m = multiple(V, C0, x)
    s = share(C0, x)
    ok = "○ 賄える" if x >= 1.15 else "× 足りない（%.2f億不足）" % (1.15 - x)
    print("  %.2f億    %5.1f%%     %5.2f億    %5.1f倍    %s" % (x, s * 100, s * V, m, ok))

print()
print("  → 調達額を 1.42億 → 0.50億 と 1/3 にしても、倍率は %.1f倍 → %.1f倍。"
      % (multiple(V, C0, 1.42), multiple(V, C0, 0.50)))
print("     持分も一緒に減るので、割り算の答えがほとんど変わらない。")
print()

print("=" * 82)
print("② キャップを下げる（調達額は1.42億のまま）")
print("=" * 82)
print("  キャップ  シード持分    取り分      倍率     創業者持分")
print("  " + "-" * 60)
for c in [6.0, 5.0, 4.0, 3.0]:
    m = multiple(V, c, X0)
    s = share(c, X0)
    founder = 42.2 - (s - SHARE0) * 100
    print("  %.1f億    %5.1f%%     %5.2f億    %5.1f倍    %.1f%%" % (c, s * 100, s * V, m, founder))
print()

print("=" * 82)
print("③ 両方下げる（調達額を絞り、キャップもそれに見合わせる）")
print("=" * 82)
print("  調達額が小さいならキャップも低く置くのが自然。放出比率を一定にした場合。")
print()
print("  調達額   キャップ  放出  シード持分   倍率    1年目を賄えるか")
print("  " + "-" * 68)
for x, c in [(1.42, 6.0), (1.20, 5.0), (1.00, 4.2), (0.80, 3.4), (0.50, 2.1)]:
    m = multiple(V, c, x)
    s = share(c, x)
    rel = x / (c + x) * 100
    ok = "○" if x >= 1.15 else "×"
    print("  %.2f億   %.1f億   %4.1f%%   %5.1f%%    %5.1f倍   %s" % (x, c, rel, s * 100, m, ok))
print()
print("  → 放出比率を保ったまま両方下げると、倍率は %.1f倍 → %.1f倍 まで上がる。"
      % (multiple(V, 6.0, 1.42), multiple(V, 2.1, 0.50)))
print("     入口の値段が下がるのに、出口は同じだから。ここが効く。")
print("     代わりに手元現金が減る。1年目に必要な約1.1億を割ると計画が回らない。")
print()

print("=" * 82)
print("では何が倍率を決めるのか")
print("=" * 82)
print("  倍率 = d × 時価総額 ÷ (キャップ + 調達額)")
print()
print("  動かせるのは3つだけ:")
print("   1. 時価総額を上げる   … P4を伸ばす。事業の話")
print("   2. キャップを下げる   … 創業者が薄まる。交渉の話")
print("   3. 希薄化 d を減らす … シリーズAを打たない。資金計画の話")
print()
print("  3 の効き方（シリーズA 3億を打たない場合）:")
D_NOA = D / 0.80 * 0.958   # 公募20%は残り、シリーズAぶんの希薄化が消える概算
for c in [6.0, 5.0, 4.0]:
    m_a = D * V / (c + X0)
    m_noa = D_NOA * V / (c + X0)
    print("     キャップ%.1f億: シリーズAあり %.1f倍 → なし %.1f倍" % (c, m_a, m_noa))
print()
print("  ただしシリーズAを打たないなら、2〜3期の赤字を自力で埋める必要がある。")
print("  P4主役案の2期は営業利益▲72百万。制作の現金でここを持たせられるかが条件。")


# ══════════════════════════════════════════════════════════════
# 調達額を下げたときのランウェイ（P4主役案の数字で）
# ══════════════════════════════════════════════════════════════
print()
print("=" * 82)
print("調達額を下げると、シリーズAまでの猶予がどれだけ縮むか")
print("=" * 82)
Y1_NEED = 109       # 1期の所要（販管費65 + 開発35 + 運転資金5 + 設立機材4）百万円
Y2_BURN = 92        # 2期の所要（営業赤字72 + 運転資金増20）百万円
print("  1期の所要 %d百万 ／ 2期の所要 %d百万（月あたり %.1f百万）" % (Y1_NEED, Y2_BURN, Y2_BURN / 12.0))
print()
print("  調達額   1期末の残     2期のどこで尽きるか        シリーズAの交渉力")
print("  " + "-" * 70)
for x in [1.42, 1.30, 1.20, 1.10, 1.00]:
    left = x * 100 - Y1_NEED
    if left < 0:
        print("  %.2f億   %+6.0f百万   1期中に尽きる              ×  計画が回らない" % (x, left))
        continue
    months = left / (Y2_BURN / 12.0)
    if months >= 9:
        judge = "○  1期の実績を見せてから臨める"
    elif months >= 5:
        judge = "△  PF公開直後に動く必要あり"
    else:
        judge = "×  実績が出る前に頭を下げる"
    print("  %.2f億   %+6.0f百万   2期%4.1fヶ月目               %s" % (x, left, months, judge))
print()
print("  ※ 1期の所要はP4主役案の前提。P4を1期から作るので、制作主軸案より開発が重い。")
