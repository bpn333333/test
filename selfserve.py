# -*- coding: utf-8 -*-
"""②-C 個人セルフサーブ（用途特化）— 自分で作れる機能

松田さんの決定（2026-09-23）
  ・③ ではなく ② に置く（ツール事業の一番下の階層。評価倍率が高い側）
  ・汎用の動画エディタは作らない。**用途特化**
  ・売上は小さく置き、③への転換とデータ量で正当化する
  ・③-A の共食いは隠さず明示的に差し引く

テンプレートは ③-A の商品にそのまま揃える。
  誕生日／記念日／ウェディング／イベント・余興／SNS用／WEBサイト用
作れるのは「テンプレートを選ぶ → 写真と名前と日付を入れる → 生成」まで。
タイムライン編集・素材ライブラリ・モバイルアプリは作らない。

★ 価格・ユーザー数・転換率・共食い率はすべて私が置いた値。
"""

Y = ["1期", "2期", "3期", "4期", "5期"]
n = 5

# ── 課金（フリーミアム）─────────────────────────────────
#   無料      テンプレートで作成・プレビュー。書き出しは透かし入り
#   都度      透かし無しの書き出し 1本 1,500円
#   使い放題  月額980円
PRICE_ONCE = 1500
PRICE_SUB = 980
ARPPU = 4000        # ★有料1人あたり年間支払額（都度と使い放題の混合）

USERS = [0, 30000, 120000, 280000, 500000]      # ★登録ユーザー（累計）
PAID_RATE = [0.00, 0.05, 0.06, 0.07, 0.08]      # ★有料転換率
OUT_PER_PAID = 2.5                               # ★有料1人あたり年間出力本数

paid = [round(USERS[i] * PAID_RATE[i]) for i in range(n)]
rev2c = [paid[i] * ARPPU / 1e6 for i in range(n)]        # 百万円
outputs = [round(paid[i] * OUT_PER_PAID) for i in range(n)]

print("=" * 92)
print("②-C 個人セルフサーブ（用途特化・フリーミアム）")
print("=" * 92)
print("  無料: テンプレート作成・プレビュー（書き出しは透かし入り）")
print("  都度: 透かし無しの書き出し %s円/本 ／ 使い放題: 月額%s円"
      % (f"{PRICE_ONCE:,}", f"{PRICE_SUB:,}"))
print()


def row(label, vals, f="{:>11,.0f}"):
    print(label.ljust(26) + "".join(f.format(v) for v in vals))


row("", Y, "{:>11}")
print("-" * 92)
row("登録ユーザー（累計）", USERS)
row("  有料転換率(%)", [r * 100 for r in PAID_RATE], "{:>11.1f}")
row("有料ユーザー", paid)
row("②-C 売上（百万円）", rev2c)
row("★ 年間出力本数（データ）", outputs)
print("=" * 92)
print()
print("  → 5期の売上は %.1f億。②全体（約40億）の %.1f%%にすぎない。"
      % (rev2c[-1] / 100, rev2c[-1] / 3996 * 100))
print("     ここは売上で正当化する機能ではない。見るべきは下の2つ。")
print()
print("  ① データ: 年 %s本の出力。うち採用されなかった中間生成物も残る。"
      % f"{outputs[-1]:,}")
print("     ③の発注データは完成品しか残らないので、モデル改善に効くのはこちら。")
print("  ② 導線: 自分でやって無理だった人が ③ に流れる。③の入口が太くなる。")
print()

# ── ③-A の共食い（SKU別に明示）──────────────────────────
# 高単価のものほど「自分で作る」に流れにくい。ウェディングは特に流れない。
A = [
    ("SNS用ショート",         5000,  25000, 0.20),
    ("誕生日ムービー",        8000,  12000, 0.25),
    ("記念日ムービー",       10000,   8000, 0.25),
    ("イベント・余興ムービー",  15000,  10000, 0.15),
    ("WEBサイト用",          25000,   6000, 0.10),
    ("ウェディングムービー",   35000,   9000, 0.05),
]
print("=" * 92)
print("③-A の共食い（5期・SKU別）")
print("=" * 92)
print("  %-24s %9s %9s %8s %9s %12s" % ("商品", "単価", "元の件数", "★共食い率", "減る件数", "GMV減(百万)"))
print("  " + "-" * 82)
cut_cnt = cut_gmv = 0
base_cnt = base_gmv = 0
for name, price, cnt, rate in A:
    dc = round(cnt * rate)
    dg = dc * price / 1e6
    cut_cnt += dc
    cut_gmv += dg
    base_cnt += cnt
    base_gmv += cnt * price / 1e6
    print("  %-24s %8s円 %8s件 %7.0f%% %8s件 %11.1f"
          % (name, f"{price:,}", f"{cnt:,}", rate * 100, f"{dc:,}", dg))
print("  " + "-" * 82)
print("  %-24s %9s %8s件 %7.0f%% %8s件 %11.1f"
      % ("合計", "", f"{base_cnt:,}", cut_cnt / base_cnt * 100, f"{cut_cnt:,}", cut_gmv))
print()
print("  ③-A GMV  %.2f億 → %.2f億（%.2f億減）" % (base_gmv / 100, (base_gmv - cut_gmv) / 100, cut_gmv / 100))
print("  ③   売上 手数料20%%なので %.2f億 減る" % (cut_gmv * 0.20 / 100))
print("  ※ 単価が高いものほど共食いしない。ウェディングは一生に一度なので自分で作らない。")
print()

print("=" * 92)
print("差し引き（5期）")
print("=" * 92)
print("  ②-C 売上          %+7.2f億" % (rev2c[-1] / 100))
print("  ③   売上（共食い）  %+7.2f億" % (-cut_gmv * 0.20 / 100))
print("  " + "-" * 34)
print("  純増              %+7.2f億" % (rev2c[-1] / 100 - cut_gmv * 0.20 / 100))
print()
print("  → 売上の純増は %.2f億しかない。**入れる理由は金額ではない。**"
      .replace("**", "") % (rev2c[-1] / 100 - cut_gmv * 0.20 / 100))
print("     ②に置いたことで、この %.2f億には③（4〜6倍）ではなく②（6〜8倍）の倍率が当たる。"
      % (rev2c[-1] / 100))
print("     そして年 %s本のデータが、AX倍率を上げる側に積み上がる。" % f"{outputs[-1]:,}")
print()
print("  ★ 作らないもの: タイムライン編集・素材ライブラリ・モバイルアプリ・汎用テンプレート")
print("     CapCutは無料、Canvaは月1,500円で全部入り。正面からは戦わない。")
