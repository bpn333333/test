# ── 配分を組み替えた3案 ─────────────────────────────────
CASES = {
    "A 現計画":        {"① 制作": 67.1, "② ツール外販": 10.5, "③ C2C手数料": 4.9},
    "B 制作を半分に":  {"① 制作": 33.6, "② ツール外販": 40.0, "③ C2C手数料": 15.0},
    "C 両方伸ばす":    {"① 制作": 67.1, "② ツール外販": 40.0, "③ C2C手数料": 15.0},
}
AX = 4.0
print("=" * 76)
print("配分を組み替えるとどうなるか")
print("=" * 76)
print("  案            売上    制作本数   人手に比例しない   ライン別評価   シード")
print("  " + "-" * 68)
for name, c in CASES.items():
    rev = sum(c.values())
    units = c["① 制作"] * 10000 / 60
    ns = (c["② ツール外販"] + c["③ C2C手数料"] + c["① 制作"] * (1 - 1 / AX)) / rev * 100
    val = c["② ツール外販"] * 7 + c["③ C2C手数料"] * 5 + c["① 制作"] * 2   # 億
    print("  %-12s %6.1f億  %7.0f本      %5.1f%%      %7.1f億   %5.1f倍"
          % (name, rev, units, ns, val, val * 100 * 0.145 / 142))
print()
print("  ※ ライン別評価はツール7倍・C2C5倍・制作2倍。シードは上場後持分14.5%・出資1.42億")
print()

