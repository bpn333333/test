# -*- coding: utf-8 -*-
"""事業③ 越境C2C発注プラットフォーム — 商品・値付け・受注件数

松田さんの指示（2026-09-23）で商品構成が決まった。
  ③-A 個人向けパッケージ    誕生日／記念日／ウェディング／イベント／SNS用／WEBサイト用
  ③-B 中小企業向けパッケージ  ※内容は①を参考に私が考える
  ③-C オーダーメイド        個人・企業。AI-botが仲介

値付けの制約（私が置いたのではなく、既存の決定から来るもの）
  1 ① 映像制作と食い合わせない。①の最安は「展示会・社内イベント 30万」なので、
    ③-B のパッケージはその下に収める。
  2 C2Cの上限は100万円（Ver1.2の決定）。オーダーメイドもこれを超えない。
  3 越境である意味は「日本の需要 × 中国の供給」。単価は日本の相場より下、件数が効く。

★ 単価・件数・手数料率はすべて私が置いた値。承認されるまで確定ではない。
  既存の一本値（5期 GMV 83億・92,000件・平均9万・手数料18%）との差は末尾で突き合わせる。
"""

Y = ["1期", "2期", "3期", "4期", "5期"]

# ── ③-A 個人向けパッケージ（定型。AI-botの仲介すら不要）──────────
# (商品, GMV単価(円), 5期件数, 立ち上がりカーブ, 考え方)
RAMP_A = [0.01, 0.07, 0.28, 0.62, 1.00]
A = [
    ("誕生日ムービー",        8000,  12000, "写真・名前を差し替えるテンプレート型"),
    ("記念日ムービー",       10000,   8000, "結婚記念日・還暦・退職"),
    ("ウェディングムービー",   35000,   9000, "オープニング／プロフィール／エンドロール"),
    ("イベント・余興ムービー",  15000,  10000, "二次会・部活・送別会"),
    ("SNS用ショート",         5000,  25000, "縦型15〜30秒。最も件数が出る"),
    ("WEBサイト用",          25000,   6000, "個人事業主・クリエイターの紹介動画"),
]

# ── ③-B 中小企業向けパッケージ（★内容は私の提案）─────────────
# ①の最安30万を超えないように設計する
RAMP_B = [0.00, 0.04, 0.22, 0.58, 1.00]
B = [
    ("会社紹介ショート",        80000,  4000, "①の企業VP標準50万の簡易版。仕様固定"),
    ("採用（小規模・1職種）",   120000,  2500, "①の採用ブランド型100万より下の帯"),
    ("商品・サービス紹介",     100000,  5000, "EC・SaaSの機能紹介"),
    ("店舗・施設紹介",         60000,  3500, "飲食・クリニック・サロン"),
    ("展示会・イベント告知",     50000,  2000, "①の展示会30万の下の帯"),
    ("SNS広告用（縦型3本）",    90000,  6000, "3本セット。運用で回す"),
]

# ── ③-C オーダーメイド（AI-botが要件を聞いて仕様に落とす）────────
RAMP_C = [0.00, 0.00, 0.15, 0.55, 1.00]
C = [
    ("個人オーダーメイド",      60000,  8000, "パッケージに収まらない個別要望"),
    ("企業オーダーメイド",     250000, 12000, "上限100万。①との違いは“当社が品質を保証しない”こと"),
]

TAKE_PKG = 0.20     # ★パッケージの手数料率。定型で当社の手間がゼロ
TAKE_CUSTOM = 0.15  # ★オーダーメイドの手数料率。単価が高いので率を下げないと直接取引に逃げる

OLD_GMV = [50, 400, 1600, 4500, 8300]     # 百万円。Ver1.2からの一本値
OLD_CNT = 92000
OLD_TAKE = 0.18


def block(title, items, ramp, take, note=""):
    print("=" * 96)
    print(title)
    print("=" * 96)
    print("  %-26s %10s %10s %12s %10s  %s"
          % ("商品", "GMV単価", "5期件数", "5期GMV(百万)", "手数料率", "考え方"))
    print("  " + "-" * 92)
    gmv5 = cnt5 = 0
    for name, price, cnt, why in items:
        g = price * cnt / 1e6
        gmv5 += g
        cnt5 += cnt
        print("  %-26s %9s円 %9s件 %11.0f %9.0f%%  %s"
              % (name, f"{price:,}", f"{cnt:,}", g, take * 100, why))
    print("  " + "-" * 92)
    print("  %-26s %9s円 %9s件 %11.0f %9.0f%%"
          % ("小計 / 平均", f"{int(gmv5 * 1e6 / cnt5):,}", f"{cnt5:,}", gmv5, take * 100))
    if note:
        print("  " + note)
    print()
    gmv_y = [gmv5 * r for r in ramp]
    cnt_y = [cnt5 * r for r in ramp]
    return gmv_y, cnt_y, gmv5, cnt5


gA, cA, gA5, cA5 = block("③-A 個人向けパッケージ（定型・テンプレート）", A, RAMP_A, TAKE_PKG,
                         "※ 1期から出す。当社の手間がかからないので、立ち上げの実績づくりに使える。")
gB, cB, gB5, cB5 = block("③-B 中小企業向けパッケージ（★内容は私の提案）", B, RAMP_B, TAKE_PKG,
                         "※ 2期から。①の最安30万を超えないよう、最高でも12万に収めた。")
gC, cC, gC5, cC5 = block("③-C オーダーメイド（AI-botが仲介）", C, RAMP_C, TAKE_CUSTOM,
                         "※ 3期から。AI-botの開発が要る。上限100万［Ver1.2の決定］。")

n = 5
gmv = [gA[i] + gB[i] + gC[i] for i in range(n)]
cnt = [cA[i] + cB[i] + cC[i] for i in range(n)]
rev = [(gA[i] + gB[i]) * TAKE_PKG + gC[i] * TAKE_CUSTOM for i in range(n)]
rev_flat = [gmv[i] * OLD_TAKE for i in range(n)]


def row(label, vals, f="{:>11,.0f}"):
    print(label.ljust(26) + "".join(f.format(v) for v in vals))


print("=" * 96)
print("③ 全体（単位 百万円・件）")
print("=" * 96)
row("", Y, "{:>11}")
print("-" * 96)
row("  ③-A 個人パッケージ GMV", gA)
row("  ③-B 中小企業 GMV", gB)
row("  ③-C オーダーメイド GMV", gC)
row("GMV 合計", gmv)
row("  （Ver1.2の一本値）", OLD_GMV)
row("取引件数", cnt)
row("平均単価（円）", [g * 1e6 / c if c else 0 for g, c in zip(gmv, cnt)])
print("-" * 96)
row("③ 売上（率を分ける・★提案）", rev)
row("③ 売上（一律18%・現行定義）", rev_flat)
row("  実効手数料率(%)", [r / g * 100 if g else 0 for r, g in zip(rev, gmv)], "{:>11.1f}")
print("=" * 96)
print()

print("=" * 96)
print("一本値との突き合わせ（5期）")
print("=" * 96)
print("  %-22s %14s %16s %10s" % ("", "Ver1.2の一本値", "積み上げ", "差"))
print("  " + "-" * 66)
print("  %-22s %13.0f億 %15.1f億 %9.1f億" % ("GMV", OLD_GMV[-1] / 100, gmv[-1] / 100,
                                             (gmv[-1] - OLD_GMV[-1]) / 100))
print("  %-22s %13s件 %15s件 %9s件" % ("取引件数", f"{OLD_CNT:,}", f"{int(cnt[-1]):,}",
                                       f"{int(cnt[-1]) - OLD_CNT:+,}"))
print("  %-22s %13s円 %15s円" % ("平均単価", f"{int(OLD_GMV[-1] * 1e6 / OLD_CNT):,}",
                                 f"{int(gmv[-1] * 1e6 / cnt[-1]):,}"))
print("  %-22s %13.0f%% %15.1f%%" % ("手数料率", OLD_TAKE * 100, rev[-1] / gmv[-1] * 100))
print("  %-22s %13.1f億 %15.1f億 %9.1f億" % ("③ 売上", OLD_GMV[-1] * OLD_TAKE / 100,
                                             rev[-1] / 100,
                                             (rev[-1] - OLD_GMV[-1] * OLD_TAKE) / 100))
print()
print("  → 件数は %s件（月 %s件・日 %s件）。単価が下がるのでGMVは一本値より小さい。"
      % (f"{int(cnt[-1]):,}", f"{int(cnt[-1] / 12):,}", f"{int(cnt[-1] / 365):,}"))
print("     平均9万は「企業オーダーメイドだけを見た数字」で、パッケージを入れると下がる。")
print("     ①と同じで、**一本値は性質の違う商品を潰していた**。".replace("**", ""))
print()
print("  ★ 判断してほしいこと")
print("    1 手数料率を商品で分ける（パッケージ20%・オーダーメイド15%）か、一律18%のままか")
print("    2 ③-B の中身（私が①から起こしたもの）でよいか")
print("    3 企業オーダーメイド 平均25万は ① の展示会30万に近い。")
print("      違いは「①は当社が品質を保証する／③は発注者が自分でやり取りする」。この線引きでよいか")
