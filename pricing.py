# -*- coding: utf-8 -*-
"""① 映像制作の単価を組み直す

これまで「単価60万円/本」を置いていた。出所は動画幹事・ムビサクの相場帯。
これは見積比較サイトの集計で、引き合いが中小企業に偏っている。
企業が実際に払っている水準とは別物であり、そこを基準にすると
  ・当社の価格が実勢の下限帯に貼りつく
  ・値引き幅（＝顧客が得るディスカウントバリュー）が絶対額で小さくなる
  ・結果、稟議が上がる理由にならない

そこでトップダウンの実額から単価を検算し、用途別のミックスで置き直す。

出所
  矢野経済研究所   BtoB映像制作市場 4,580億円
  電通            2025年 インターネット広告制作費 4,922億円（前年比104.0%）
  国税庁          令和5年度分 会社標本調査 法人数 295万6,717社
  用途別の価格帯   複数の制作会社・比較サイトの公表レンジ（下表に個別記載）

⚠ 用途構成比と難度係数は当社の［仮置き］。単価レンジは公表値。
"""

# ── 1. トップダウンの検算 ──────────────────────────────
SAM_BTOB = 4580.0          # 億円。矢野経済研究所 BtoB映像制作市場
HOJIN = 2956717            # 社。国税庁 令和5年度分 会社標本調査
TOHOKU = 477.0             # 億円。東北新社 2026/3期

print("=" * 94)
print("検算① — 市場規模を単価で割ると、年間の本数が出る")
print("=" * 94)
print("  BtoB映像制作市場 %.0f億円（矢野経済研究所）を、単価で割る" % SAM_BTOB)
print()
print("  想定単価      年間本数        法人1社あたり     妥当か")
print("  " + "-" * 74)
for price in [60, 100, 200, 300, 500]:
    units = SAM_BTOB * 1e8 / (price * 1e4)
    per = units / HOJIN
    if price <= 60:
        v = "× 法人の4社に1社が毎年発注する計算。過大"
    elif price <= 100:
        v = "△ 6社に1社。まだ多い"
    elif price <= 200:
        v = "○ 13社に1社"
    else:
        v = "○ 現実的"
    print("  %5d万/本   %9.0f本   %10.3f本   %s" % (price, units, per, v))
print()
print("  → 60万で割ると年76万本。法人295.7万社に対して多すぎる。")
print("     市場平均の単価は、少なくとも百万円台と見るのが自然。")
print()

print("=" * 94)
print("検算② — 大手1社に当てはめてみる")
print("=" * 94)
for price in [60, 1000, 3000]:
    units = TOHOKU * 1e8 / (price * 1e4)
    print("  東北新社 %.0f億 ÷ %5d万/本 = 年 %7.0f本（月 %6.0f本）%s"
          % (TOHOKU, price, units, units / 12,
             "  ← CM制作会社の実態と合わない" if price == 60 else ""))
print()
print("  → 大手が受けているのはテレビCM（制作費1,000万〜1億）。桁が違う。")
print("     60万は市場の底のほうであって、企業が払っている水準ではない。")
print()

# ── 2. 用途別の単価ミックス ────────────────────────────
# (用途, 企業の現行支払（中央値・万円）, レンジ, 難度係数, 構成比, 出所)
BASE_COST = 20.5      # 万円。AX4倍時の1本あたり原価（従来の前提）
DISCOUNT = 0.50       # 当社価格 ＝ 現行支払の50%［仮置き］

MIX = [
    ("ブランドムービー・Web CM", 500, "300〜1,000万", 3.0, 0.15,
     "ブランディング目的の映像。採用ブランディング動画の予算記事ほか"),
    ("企業VP・採用（ブランド型）", 200, "150〜300万", 1.8, 0.35,
     "ドラマ仕立て・密着。ワンキャリア／crevo の採用動画相場"),
    ("企業VP・会社紹介（標準）", 100, "50〜150万", 1.0, 0.35,
     "会社紹介・オフィスツアー。デッキp9の★1行目"),
    ("展示会・社内イベント", 60, "20〜100万", 0.8, 0.15,
     "デッキp9の★2行目"),
]
OUT_OF_SCOPE = [
    ("テレビCM（制作費）", 3000, "1,000万〜1億", "部分適用にとどまる。①では取らない"),
    ("BtoBマーケ・SNS量産", 20, "10〜30万", "③ C2Cへ回す。①では赤字になる（下記）"),
]

print("=" * 94)
print("用途別の単価ミックス — 当社価格は「企業の現行支払の50%」で置く")
print("=" * 94)
print("  用途                        現行支払    当社価格   顧客の削減   当社原価   粗利率   構成比")
print("  " + "-" * 88)
pw = cw = 0.0
for name, cur, rng, k, share, src in MIX:
    price = cur * DISCOUNT
    cost = BASE_COST * k
    print("  %-26s %6d万  %7.0f万  %8.0f万  %7.1f万  %5.1f%%  %5.0f%%"
          % (name, cur, price, cur - price, cost, (1 - cost / price) * 100, share * 100))
    pw += price * share
    cw += cost * share
print("  " + "-" * 88)
print("  %-26s %6.0f万  %7.1f万  %8.1f万  %7.1f万  %5.1f%%  %5.0f%%"
      % ("加重平均", pw / DISCOUNT, pw, pw / DISCOUNT - pw, cw, (1 - cw / pw) * 100, 100))
print()
print("  ＜①では取らない帯＞")
for name, cur, rng, why in OUT_OF_SCOPE:
    print("  %-26s %6d万  %s" % (name, cur, why))
cheap_price = 20 * DISCOUNT
cheap_cost = BASE_COST * 0.5
print()
print("  BtoBマーケ・SNS量産が①で成立しない理由:")
print("    現行20万 → 当社価格 %.0f万。原価は難度0.5倍でも %.1f万。粗利 %.1f万（%.0f%%）。"
      % (cheap_price, cheap_cost, cheap_price - cheap_cost,
         (1 - cheap_cost / cheap_price) * 100))
print("    受注・検収・請求の手間が1本あたり同じだけかかるので、ここは人を介さない③でしか回らない。")
print()

print("=" * 94)
print("従来の前提と、置き直した後")
print("=" * 94)
print("  %-22s %12s %12s" % ("", "従来", "置き直し後"))
print("  " + "-" * 50)
print("  %-22s %11s %12s" % ("単価の出所", "見積サイト相場帯", "企業の現行支払×50%"))
print("  %-22s %10.1f万 %11.1f万" % ("1本あたり単価", 60.0, pw))
print("  %-22s %10.1f万 %11.1f万" % ("1本あたり原価", BASE_COST, cw))
print("  %-22s %10.1f%% %11.1f%%" % ("粗利率", (1 - BASE_COST / 60) * 100, (1 - cw / pw) * 100))
print("  %-22s %10s %11.0f万" % ("顧客が1本で浮く額", "—（示せない）", pw / DISCOUNT - pw))
print()
print("  → 単価は %.2f倍になるが、粗利率はほぼ変わらない（%.1f%% → %.1f%%）。"
      % (pw / 60, (1 - BASE_COST / 60) * 100, (1 - cw / pw) * 100))
print("     原価は顧客の予算ではなく、カット数・尺・修正回数で決まるため。")
print("     **上の帯に行くほど、価格は上がるが原価は比例しない。** これが値付けの筋。"
      .replace("**", ""))
print()

# ── 3. 5期の①にどう効くか ─────────────────────────────
UNITS_B = 5594
print("=" * 94)
print("5期の① 映像制作 — 本数をどうするか")
print("=" * 94)
SAM_2031 = 2238.0   # 億円。2031年SAM（prod_ax.py）
print("  案            本数     単価      ① 売上    SAMシェア   顧客が浮かせる総額   AXの負荷")
print("  " + "-" * 86)
for label, units in [("現状(B案)", UNITS_B), ("① 本数を維持", UNITS_B), ("② 売上を維持", int(33.6e8 / (pw * 1e4)))]:
    price = 60.0 if label == "現状(B案)" else pw
    rev = units * price / 10000.0
    save = units * (price / DISCOUNT - price) / 10000.0 if label != "現状(B案)" else 0
    gig = units * (1 / 120.0 + 1 / 90.0) / 4
    print("  %-12s %6d本  %6.1f万  %7.1f億   %6.2f%%   %12s   委託%.0f名"
          % (label, units, price, rev, rev / SAM_2031 * 100,
             ("%.0f億" % save) if save else "—", gig))
print()
print("  ① 本数を維持 … 稼働は今と同じまま、① が 33.6億 → %.1f億。" % (UNITS_B * pw / 10000.0))
print("     人手に比例しない収益の比率は下がる（①の構成比が上がるため）。")
print("  ② 売上を維持 … ① は 33.6億のまま、本数が %d本 → %d本。"
      % (UNITS_B, int(33.6e8 / (pw * 1e4))))
print("     AX倍率の前提がさらに軽くなる。計画の一番重い仮定が緩む。")
