"""組織を組み直す — 社員はPM中心、開発はオフショア業務委託、管理はAX化で極小

松田さんの指示（2026-09-23）
  ・エンジニアの人数が多すぎる。基本的に PM を社員として、
    あとは中国・ベトナム・東ヨーロッパに業務委託する構成に
  ・管理・コーポレートの人数比率が多い。AX化で極小に

旧: モデル開発エンジニアを社員で40名（5期・社員61名中）抱える
新: モデル開発PMを社員で8名、その下にオフショア40名を業務委託

オフショア単価（国別・実測）
  オフショア開発.com 2026年2月更新。シニアエンジニアの人月単価。
  ⚠ 中国は最も高い（71.7万/月）。「中国の方が安い」は成り立たない。
    安いのは中国の**クリエイター**（剪辑師 月18.8万・雇用ベース）であって、
    エンジニアの受託単価ではない。両者は性質が違う。
  ⚠ 東欧はこの調査に含まれないため★推定。
"""

Y = ["1期", "2期", "3期", "4期", "5期"]
n = 5
BURDEN = 1.16

# ── オフショア単価（国別・実測）───────────────────────────
# オフショア開発.com 2026年2月13日更新。シニアエンジニアの人月単価（万円）
# ⚠ 東欧はこの調査に含まれていない。当社の★推定。
SENIOR = {"ミャンマー": 40.0, "インド": 45.0, "フィリピン": 47.5, "ベトナム": 50.0,
          "バングラデシュ": 52.5, "中国": 71.7, "東欧★": 80.0}
SRC = {"東欧★": "★推定（この調査に東欧は含まれない）"}

print("=" * 92)
print("オフショア単価（シニアエンジニア・人月）— オフショア開発.com 2026")
print("=" * 92)
print("  %-14s %10s %12s  %s" % ("国", "月額(万)", "年額(万)", "ベトナム比"))
print("  " + "-" * 62)
for k, v in sorted(SENIOR.items(), key=lambda x: x[1]):
    mark = "  ← 中国は最も高い" if k == "中国" else ""
    print("  %-14s %10.1f %12.0f %11.2f倍%s" % (k, v, v * 12, v / SENIOR["ベトナム"], mark))
print()
print("  ⚠ 中国はオフショア先として**最も高い**。R&D投資でエンジニア単価が高騰している。"
      .replace("**", ""))
print("     私は「ベトナム比1.3倍」と推定していたが、実測は 1.43倍だった。")
print("     そして「中国の方が安い」という直感は、**クリエイターの話とエンジニアの話が混ざっている**。"
      .replace("**", ""))
print("     中国の剪辑師は月18.8万円（雇用ベース）。エンジニアの受託単価は71.7万円。")
print("     前者は直接契約の賃金、後者はベンダーのマージンが乗った受託価格で、性質が違う。")
print()

MIXES = {
    "現行（中国・ベトナム・東欧）": {"ベトナム": 0.50, "中国": 0.30, "東欧★": 0.20},
    "中国を外す（ベトナム・インド・比）": {"ベトナム": 0.50, "インド": 0.30, "フィリピン": 0.20},
    "ベトナム単独": {"ベトナム": 1.00},
}
print("=" * 92)
print("構成比の選択肢")
print("=" * 92)
print("  %-34s %12s %12s %14s" % ("構成", "月額(万)", "年額(万)", "5期40名の年額"))
print("  " + "-" * 78)
RES = {}
for name, mx in MIXES.items():
    m = sum(SENIOR[k] * w for k, w in mx.items())
    RES[name] = m * 12
    print("  %-34s %12.1f %12.0f %13.1f億" % (name, m, m * 12, m * 12 * 40 / 10000))
print()
base = RES["現行（中国・ベトナム・東欧）"]
alt = RES["中国を外す（ベトナム・インド・比）"]
print("  → 中国を外すと 1人あたり年 %.0f万 安くなる。40名なら年 %.2f億。"
      % (base - alt, (base - alt) * 40 / 10000))
print()
print("  ＜中国を使う理由が残るとすれば＞")
for t in ["制作パートナーが既に中国にいる。同じ会社に開発も出せる（窓口が1つで済む）",
          "中国語圏のデータ・モデル対応",
          "クリエイターネットワークと開発チームが近い（③のAI-botは中国語UIも要る）"]:
    print("    ・" + t)
print("  ＜外す理由＞")
print("    ・単価が最も高い。エンジニアリングで中国を使うコスト上の理由はない")
print()

MIX = MIXES["現行（中国・ベトナム・東欧）"]     # ★松田さんの指示どおり据え置き
OFF_MONTH = sum(SENIOR[k] * w for k, w in MIX.items())
OFF_YEAR = OFF_MONTH * 12
print("  ※ 構成比は松田さんの指示（中国・ベトナム・東欧）のまま据え置き。年 %.0f万で計算する。"
      % OFF_YEAR)
print()

# ── 社員 ───────────────────────────────────────────────
ROLE = {
    "経営・CxO": 900,
    "モデル開発PM": 950,
    "制作統括": 650,
    "事業開発・アライアンス": 700,
    "クリエイターネットワーク統括": 600,
    "管理・コーポレート": 550,
}
HEADS = {
    "経営・CxO":                [1, 1, 2, 3, 3],
    "モデル開発PM":              [1, 2, 4, 6, 8],
    "制作統括":                 [1, 2, 3, 3, 3],
    "事業開発・アライアンス":      [1, 2, 4, 5, 6],
    "クリエイターネットワーク統括": [1, 1, 2, 3, 3],
    "管理・コーポレート":         [0, 1, 1, 2, 2],
}
PER_PM = 5      # ★PM1名あたりのオフショアエンジニア数
OFF_HEADS = [HEADS["モデル開発PM"][i] * PER_PM for i in range(n)]
OFF_COST = [OFF_HEADS[i] * OFF_YEAR / 100 for i in range(n)]   # 百万円

heads = [sum(HEADS[r][i] for r in ROLE) for i in range(n)]
pay = [sum(HEADS[r][i] * ROLE[r] * BURDEN for r in ROLE) / 100 for i in range(n)]

# 旧構成
OLD_ROLE = {"経営・CxO": 900, "モデル開発エンジニア": 850, "制作統括": 650,
            "事業開発・アライアンス": 700, "クリエイターネットワーク統括": 600,
            "管理・コーポレート": 550}
OLD_HEADS = {"経営・CxO": [1, 1, 2, 3, 3], "モデル開発エンジニア": [2, 6, 16, 28, 40],
             "制作統括": [1, 2, 3, 3, 3], "事業開発・アライアンス": [1, 2, 4, 5, 6],
             "クリエイターネットワーク統括": [1, 1, 2, 3, 3], "管理・コーポレート": [0, 1, 2, 4, 6]}
old_heads = [sum(OLD_HEADS[r][i] for r in OLD_ROLE) for i in range(n)]
old_pay = [sum(OLD_HEADS[r][i] * OLD_ROLE[r] * BURDEN for r in OLD_ROLE) / 100 for i in range(n)]


def row(lab, vals, f="{:>10,.0f}"):
    print(lab.ljust(28) + "".join(f.format(v) for v in vals))


print("=" * 92)
print("社員（PM中心）")
print("=" * 92)
print("  職種".ljust(28) + "年収".rjust(8) + "".join("%10s" % y for y in Y))
print("  " + "-" * 78)
for r in ROLE:
    print("  %-26s %6d万" % (r, ROLE[r]) + "".join("%10d" % HEADS[r][i] for i in range(n)))
print("  " + "-" * 78)
row("  社員数 合計", heads)
row("  人件費（百万円）", pay)
row("  うち 管理・コーポレート比率", [HEADS["管理・コーポレート"][i] / heads[i] * 100 for i in range(n)],
    "{:>9.1f}%")
print()

print("=" * 92)
print("業務委託（オフショア開発）")
print("=" * 92)
row("  PM（社員）", HEADS["モデル開発PM"])
row("  オフショアエンジニア", OFF_HEADS)
row("  開発委託費（百万円）", OFF_COST)
print()
print("  ★ PM1名あたり %d名。ブリッジは PM が兼ねる前提。" % PER_PM)
print()

print("=" * 92)
print("旧構成との比較")
print("=" * 92)
print("  %-26s" % "" + "".join("%10s" % y for y in Y))
print("  " + "-" * 78)
row("  旧 社員数", old_heads)
row("  新 社員数", heads)
row("  差", [heads[i] - old_heads[i] for i in range(n)], "{:>+10,.0f}")
print("  " + "-" * 78)
row("  旧 人件費", old_pay)
row("  新 人件費", pay)
row("  新 開発委託費", OFF_COST)
row("  新 合計（人件費＋委託）", [pay[i] + OFF_COST[i] for i in range(n)])
row("  差（対 旧人件費）", [pay[i] + OFF_COST[i] - old_pay[i] for i in range(n)], "{:>+10,.0f}")
print()
print("  → 5期の社員は %d名 → %d名（%+d名）。" % (old_heads[-1], heads[-1], heads[-1] - old_heads[-1]))
print("     人件費は %.0f → %.0f百万。開発委託費 %.0f百万を足すと %.0f百万で、旧より %+.0f百万。"
      % (old_pay[-1], pay[-1], OFF_COST[-1], pay[-1] + OFF_COST[-1],
         pay[-1] + OFF_COST[-1] - old_pay[-1]))
print("     **コストはほぼ変わらない。変わるのは社員数**。".replace("**", ""))
print("     1人あたりの単価はオフショアの方が安いが（年%.0f万 vs 日本 %.0f万）、"
      % (OFF_YEAR, 950 * BURDEN))
print("     人数を増やせるぶん相殺される。狙いはコスト削減ではなく組織の身軽さ。")
print()

print("=" * 92)
print("管理・コーポレートのAX化")
