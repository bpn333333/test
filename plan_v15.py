"""Ver1.5 の5年計画 — 単価を実勢に、本数を営業体制から積み上げる

Ver1.4 からの変更は ① 映像制作だけ。②③ は据え置き。

  単価   60万（見積サイトの相場帯）→ 94.5万（企業の現行支払×50%）  … pricing.py
  本数   SAMの1.5%からの逆算 → アカウント×リピートの積み上げ        … sales.py
  原価   一律20.5万 → 用途ミックスの難度係数を掛ける

結果として ① は 33.6億 → 35.7億。売上はほぼ変わらないが、
本数が 5,594 → 3,780本 に減るため、AX倍率への依存が下がる。

【Ver1.4から変えたもの】指示されたもの
  単価   60万（見積サイトの相場帯）→ 94.5万（企業の現行支払×50%）  … pricing.py
  本数   SAMの1.5%からの逆算 → アカウント×リピートの積み上げ        … sales.py

【Ver1.4から変えたもの】松田さんの決定（2026-09-23）
  原価   一律 20.5万 → 難度係数 × 基準原価（5期 31.8万）。工数にも同じ係数が効く
  ①     BtoBマーケ・SNS量産帯は ③ C2C へ回す（①は企業向け4商品のみ）
  ②     チェックポイントと工程ツールを別売り／LoRA個別構築は②の売上／法人は2階建て
         → 法人ACV 250-320万 の一本値を、積み上げの 265-326万 に置き換え

【なお私の判断で入れたもの】
  原価   一律 20.5万 → 難度係数 × 基準原価（5期 31.8万）
         理由: 単価だけ1.57倍にして原価を据え置くと粗利率が65.8%→78.3%に跳ね、
         利益を水増しすることになる。難度係数は新しい定義なので、使うかを決めてほしい。
  費用   代理店手数料を新設（①売上 × 代理店経由比率 × 15%）
         理由: sales.pyで代理店チャネルを置いたため。獲得費率6%は変えていない。

【変えていないもの】
  ② ツール外販、③ C2C、社員数・人件費、研究開発費、BPO、獲得費率6%、
  その他販管費率4%、AX倍率、シード持分14.5%

⚠ AX倍率・担当社数・リピート本数・契約数・GMV・難度係数はすべて［仮置き］。
"""

Y = ["1期", "2期", "3期", "4期", "5期"]
n = 5

# ── ① 映像制作（sales.py / pricing.py から）──────────────
UNITS = [60, 304, 1215, 2543, 3780]          # sales.py（営業体制の積み上げ）

# 商品マスタ（products.py）。単価・難度係数・構成比から、平均単価と平均難度を導出する。
# ★単価＝企業の現行支払×(1-値引率)、難度係数、構成比 は私が置いた値
#   事例が溜まるほど上の帯が取れるので、構成比は年を追って上にシフトさせている。
SKU1 = [
    # 商品                     現行支払 値引率 難度  構成比（1期→5期）
    ("ブランドムービー・Web CM",     500, 0.50, 3.00, [0.04, 0.08, 0.12, 0.13, 0.15]),
    ("企業VP・採用（ブランド型）",    200, 0.50, 1.80, [0.25, 0.28, 0.31, 0.34, 0.35]),
    ("企業VP・会社紹介（標準）",      100, 0.50, 1.00, [0.46, 0.42, 0.38, 0.36, 0.35]),
    ("展示会・社内イベント映像",       60, 0.50, 0.80, [0.25, 0.22, 0.19, 0.17, 0.15]),
]
PRICE = [sum(c * (1 - d) * m[i] for _, c, d, _, m in SKU1) for i in range(5)]
DIFF = [sum(k * m[i] for *_, k, m in SKU1) for i in range(5)]
AX = [1.0, 1.5, 2.2, 3.0, 4.0]
DIRECTION_BASE = 20.0


def cost_unit(ax, diff):
    """1本あたり原価（万円）。難度係数は商品構成比から導出される"""
    return diff * (12.0 + DIRECTION_BASE / ax + 2.0 + 1.5)


# ── ② ツール外販（据え置き）────────────────────────────
CORP = [0, 15, 100, 320, 600]
CORP_ACV = [0, 265, 290, 308, 326]   # products.py の積み上げ（2階建て・別売り）
INDIE = [0, 0, 2000, 8000, 17000]
INDIE_ACV = 12
# ②-C 個人セルフサーブ（用途特化）。selfserve.py
SELF = [0, 6, 29, 78, 160]

# ── ③ 越境C2C（c2c.py の商品別積み上げ）────────────────
# ③-A 個人パッケージ / ③-B 中小企業パッケージ / ③-C オーダーメイド
# ★手数料率はパッケージ20%・オーダーメイド15%（要判断）。一律18%なら C2C_FLAT を使う
# c2c.py の積み上げ（クリエイター側の受注判断から価格帯を決め、期待値で置いたもの）
# ②-C セルフサーブの共食いは c2c.py 側で既に差し引き済み
GMV = [6, 66, 460, 1290, 2185]
C2C_BUILD = [1, 13, 84, 228, 382]
OLD_GMV = [50, 400, 1600, 4500, 8300]   # Ver1.2の一本値（参考。ここには寄せない）
CANNIB_GMV = [0, 0, 0, 0, 0]            # c2c.py で処理済み

# ── 社員（据え置き）────────────────────────────────────
BURDEN = 1.16
ROLE = {"経営・CxO": 900, "モデル開発エンジニア": 850, "制作統括": 650,
        "事業開発・アライアンス": 700, "クリエイターネットワーク統括": 600, "管理・コーポレート": 550}
HEADS = {
    "経営・CxO":                [1, 1,  2,  3,  3],
    "モデル開発エンジニア":       [2, 6, 16, 28, 40],
    "制作統括":                 [1, 2,  3,  3,  3],
    "事業開発・アライアンス":     [1, 2,  4,  5,  6],
    "クリエイターネットワーク統括": [1, 1,  2,  3,  3],
    "管理・コーポレート":         [0, 1,  2,  4,  6],
}
BPO = [0, 10, 120, 450, 1000]
RND = [30, 120, 450, 1000, 1600]
ACQ1 = 0.06      # ①売上に対する獲得費率。Ver1.4から変えない
AGENCY_SHARE = [0.0, 0.053, 0.099, 0.147, 0.159]  # ①売上に占める代理店経由の割合（sales.py）
AGENCY_FEE = 0.15                                 # 代理店手数料率［仮置き］
ACQ2 = 0.15
ACQF = [6, 40, 90, 150, 200]

PY_PER_UNIT = 1.0 / 120 + 1.0 / 90
TOOL = [round(CORP[i] * CORP_ACV[i] / 100.0 + INDIE[i] * INDIE_ACV / 100.0) + SELF[i]
        for i in range(n)]
C2C = C2C_BUILD


def calc():
    out = []
    for i in range(n):
        p1 = UNITS[i] * PRICE[i] / 100.0
        rev = p1 + TOOL[i] + C2C[i]
        cu = cost_unit(AX[i], DIFF[i])
        gp = p1 * (1 - cu / PRICE[i]) + TOOL[i] * 0.80 + C2C[i] * 0.85
        heads = sum(HEADS[r][i] for r in ROLE)
        pay = sum(HEADS[r][i] * ROLE[r] * BURDEN for r in ROLE) / 100.0
        acq = p1 * ACQ1 + TOOL[i] * ACQ2 + ACQF[i]
        agf = p1 * AGENCY_SHARE[i] * AGENCY_FEE   # 新設。獲得費とは別に立てる
        sga = rev * 0.04
        op = gp - pay - BPO[i] - RND[i] - acq - agf - sga
        ns = TOOL[i] + C2C[i] + p1 * (1 - 1.0 / AX[i])
        out.append(dict(p1=p1, rev=rev, gp=gp, cu=cu, heads=heads, pay=pay, op=op, ns=ns,
                        gig=UNITS[i] * PY_PER_UNIT * DIFF[i] / AX[i], acq=acq, agf=agf, sga=sga,
                        saving=UNITS[i] * PRICE[i] / 100.0))
    return out


R = calc()


def row(label, vals, f="{:>9,.0f}"):
    print(label.ljust(26) + "".join(f.format(v) for v in vals))


